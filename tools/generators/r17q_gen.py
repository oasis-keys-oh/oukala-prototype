"""Round 17 Agent Q: parse the project decisions log, the status doc and the requirements register summary into
mod_r17q_a_data.js (window.R17Q_DATA). Run: python3 tools/generators/r17q_gen.py   (reads tools/generators/docs/r17q/ and docs/spec/register_summary.md; those inputs are not in the repo, see tools/README.md). Writes src/mod_r17q_a_data.js, or SRC=<folder>."""
import re,json,os,hashlib,datetime
here=os.path.dirname(os.path.abspath(__file__))
SRC=os.environ.get('SRC') or os.path.join(here,'..','..','src')
rd=lambda p:open(os.path.join(here,p),encoding='utf-8').read()
log=rd('docs/r17q/oukala-decisions-log.md');stat=rd('docs/r17q/oukala-v4-status.md');reg=rd('docs/spec/register_summary.md')
NAMING="Naming: no rename until a trademark search clears a shortlist; candidate names that collide with existing products in the same field were dropped."
RULE="Naming rule: no outside organization's brand names and no accounting-standard names appear in product text. The sample customer is Meridian Standards Foundation."
def clean(s):
    s=s.replace(chr(8212),'-').replace(chr(8211),'-').strip()
    s=s.replace("pending Omar","pending the product owner").replace("until Omar chooses","until the product owner chooses")
    s=s.replace("Omar's own","The product owner's own")
    s=re.sub(r"\bOmar\b","the product owner",s)
    s=s.replace("GAAP vault notes","Accounting-reference vault notes").replace("The FAF IT financial model","The IT financial model")
    if re.search(r"Trellis|Keel|Orchestr8|Govern8|Autom8Ops|ValueAgent|Katelyn|Ballast|Guardrail Tech",s):return NAMING
    if re.search(r"\b(FAF|Codification|ASU|ASC|FASB|GASB)\b",s):return RULE
    return s
RSN=re.compile(r"\b(because|so that|so the|so each|so a |so it|since|to keep|to avoid|to stop|to make sure|rather than|instead of|reason)\b",re.I)
CON=re.compile(r"\b(enforced|blocks?|blocked|becomes|take[s]? effect|requires?|required|therefore|means|only|never|must|needs?|no rename|supersedes|exceptions? expire|persist)\b",re.I)
def split_sent(t):
    t=clean(t);parts=re.split(r"(?<=[.;])\s+(?=[A-Z(])",t)
    return [p.strip().rstrip(';') for p in parts if p.strip()]
rows=[];cur=None;n=0
for line in log.splitlines():
    m=re.match(r"^##\s+(.*)",line)
    if m:
        h=m.group(1).strip();cur=None
        if h.lower().startswith('still open'):cur=None;continue
        d=re.search(r"(20\d\d-\d\d-\d\d)",h);r=re.search(r"Round (\d+)",h)
        date=d.group(1) if d else ''
        if not date: continue
        rnd='R'+r.group(1) if r else ('R10' if 'later' in h else 'Plan')
        cur={'date':date,'round':rnd,'head':h};continue
    m=re.match(r"^-\s+(.*)",line)
    if m and cur:
        s=split_sent(m.group(1));
        if not s:continue
        dec=s[0];rest=s[1:];rs=[x for x in rest if RSN.search(x)];cs=[x for x in rest if x not in rs and CON.search(x)]
        other=[x for x in rest if x not in rs and x not in cs]
        if any(r['decision']==dec for r in rows):continue
        if not rs and RSN.search(dec):
            # reason sits in the first sentence after a because/so clause
            mm=re.split(r"\b(because|so that|since)\b",dec,maxsplit=1,flags=re.I)
            if len(mm)==3 and len(mm[0])>25:dec=mm[0].strip(' ,');rs=[(mm[1]+mm[2]).strip()]
        n+=1
        rows.append({'id':'D-%03d'%n,'date':cur['date'],'round':cur['round'],'decision':dec,'reason':' '.join(rs),'consequence':' '.join(cs),'detail':' '.join(other),'full':clean(m.group(1))})
for r in rows:
    pass
# register summary numbers
def tbl(title):
    m=re.search(r"###\s+"+re.escape(title)+r"\s*\n\n\|[^\n]*\n\|[^\n]*\n((?:\|[^\n]*\n?)+)",reg)
    out=[]
    if m:
        for l in m.group(1).strip().splitlines():
            c=[x.strip() for x in l.strip('|').split('|')]
            if len(c)>=2 and c[0]!='Total':out.append([c[0],int(c[1])])
    return out
tot=int(re.search(r"Requirement rows:\s*(\d+)",reg).group(1));ep=int(re.search(r"Epics:\s*(\d+)",reg).group(1));st=int(re.search(r"Story seeds:\s*(\d+)",reg).group(1))
built=re.search(r"Build read:\s*`([^`]+)`",reg);ext=re.search(r"extracted\s+([0-9-]+)",reg)
data={'generated':datetime.date.today().isoformat(),
 'sources':[{'file':f,'bytes':len(rd(f).encode()),'sha':hashlib.sha1(rd(f).encode()).hexdigest()[:10]} for f in ['docs/r17q/oukala-decisions-log.md','docs/r17q/oukala-v4-status.md','docs/spec/register_summary.md']],
 'decisions':rows,
 'register':{'rows':tot,'epics':ep,'stories':st,'build':built.group(1) if built else '','extracted':ext.group(1) if ext else '','byModule':tbl('Counts by module'),'byCategory':tbl('Counts by category'),'byPriority':tbl('Counts by priority')}}
js="/* generated by r17q_gen.py from docs/r17q and docs/spec/register_summary.md; do not edit by hand */\nwindow.R17Q_DATA="+json.dumps(data,ensure_ascii=False,separators=(',',':'))+";\n"
open(os.path.join(SRC,'mod_r17q_a_data.js'),'w',encoding='utf-8').write(js)
print(len(rows),'decisions;',tot,'register rows;',len(js),'bytes')
for r in rows[:6]+rows[-3:]:print(r['id'],r['date'],r['round'],'|',r['decision'][:80],'|',r['reason'][:60],'|',r['consequence'][:60])
